import json
I = json.load(open('C:/t/ev-oa/payload/inventory.json'))
M, F, R = I['merged_payload'], I['final_mapped'], I['pwml_ir']
triples = [
    ('compound', 'entities.compounds', 'entities.compounds', 'entities.compounds'),
    ('protein', 'entities.proteins', 'entities.proteins', 'entities.proteins'),
    ('protein complex', 'entities.protein_complexes', 'entities.protein_complexes', 'entities.protein_complexes'),
    ('nucleic acid (gene)', 'entities.nucleic_acids', 'entities.nucleic_acids', 'entities.nucleic_acids'),
    ('element collection', 'entities.element_collections', 'entities.element_collections', 'entities.element_collections'),
    ('bound', None, None, 'entities.bounds'),
    ('reaction', 'processes.reactions', 'processes.reactions', 'processes.reactions'),
    ('transport', 'processes.transports', 'processes.transports', 'processes.transports'),
    ('interaction / relation', 'processes.interactions', 'processes.interactions', 'processes.interactions'),
    ('subcellular location', 'entities.subcellular_locations', 'entities.subcellular_locations', 'subcellular_locations'),
    ('biological state (compartment context)', 'biological_states', 'biological_states', 'biological_states'),
    ('organism (species)', 'entities.species', 'entities.species', 'species'),
    ('tissue', 'entities.tissues', 'entities.tissues', 'tissues'),
    ('cell type', 'entities.cell_types', 'entities.cell_types', 'cell_types'),
    ('element location (placement of an entity in a state)', 'element_locations.compound_locations', 'element_locations.compound_locations', 'locations'),
    ('pathway metadata', None, None, 'pathway'),
]
SKIP = ('provenance_lineage', 'mapping_meta', 'db_match')


def cell(S, b, f):
    if not b:
        return '-'
    B = S['buckets'].get(b)
    if not B or f not in B['fields']:
        return 'absent'
    x = B['fields'][f]
    return f"{x['n']}/{B['n_items']} ({'/'.join(sorted(x['types']))})"


out = ['# A. Field inventory per stage (generated by render_all.py from inventory.json)', '',
       'Corpus: merged_payload and final_mapped = 152 canonical runs (quarantine_ok); pwml_ir = the 62 of them that exported a PWML IR.',
       'Cells are n_present/n_items (python type). "absent" = field never occurs in that stage. Nested fields are shown as a.b or a[].b.',
       'Blobs (provenance_lineage, mapping_meta, db_match) are listed once, not expanded. Item counts are in each heading.', '']
for lab, bm, bf, bi in triples:
    nm = M['buckets'].get(bm, {}).get('n_items') if bm else None
    nf = F['buckets'].get(bf, {}).get('n_items') if bf else None
    ni = R['buckets'].get(bi, {}).get('n_items') if bi else None
    out.append(f'## {lab}  (items: merged {nm}, final_mapped {nf}, pwml_ir {ni})')
    out.append('')
    out.append('| field | merged_payload | final_mapped (frozen) | pwml_ir |')
    out.append('|---|---|---|---|')
    names = set()
    for S, b in ((M, bm), (F, bf), (R, bi)):
        if b and b in S['buckets']:
            names |= set(S['buckets'][b]['fields'])
    for n in sorted(names):
        out.append(f"| {n} | {cell(M, bm, n)} | {cell(F, bf, n)} | {cell(R, bi, n)} |")
    out.append('')
open('C:/t/ev-oa/payload/A_field_inventory.md', 'w', encoding='utf-8').write('\n'.join(out))
print(len(out), 'lines')
