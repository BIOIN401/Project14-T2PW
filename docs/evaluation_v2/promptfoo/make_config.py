"""Generate promptfooconfig.yaml from whatever prompt variants are on disk.

Ten hand-written provider blocks would drift from the variant files the moment one is
renamed. This globs the variants directory instead, so the config always matches what is
actually there, and prints the count so a missing variant is visible before any call is
billed.

Each variant becomes its own promptfoo PROVIDER rather than a promptfoo PROMPT: the
provider reads the system prompt from disk, which keeps ~35,000 characters of JSON-shaped
text out of Nunjucks templating. See provider.py for why that matters.

Usage::

    python docs/evaluation_v2/promptfoo/make_config.py \
      --variants <dir of v*.txt> \
      --text C:/t/eval-fulltext/PMC319880.r3.txt \
      --pathway "Ara operon inactivation (autoregulation of AraC)" \
      --organism "Escherichia coli" \
      --out-dir C:/t/promptfoo-out/pw701720
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import List, Optional, Sequence

HERE = Path(__file__).resolve().parent


def _q(value: str) -> str:
    """YAML-safe double-quoted scalar."""

    return json.dumps(str(value))


def build(variants: Sequence[Path], *, text: str, pathway: str, organism: str,
          scope: str, out_dir: str, temperature: float, max_tokens: int) -> str:
    lines: List[str] = [
        "# GENERATED by make_config.py -- edit that script, not this file.",
        "description: Stage-1 extraction prompt comparison, one provider per variant",
        "",
        "prompts:",
        "  # The system prompt is NOT here on purpose: each provider loads its own from",
        "  # disk, so no variant passes through Nunjucks templating. This placeholder",
        "  # exists only because promptfoo requires a prompt entry.",
        "  - \"extraction is driven by the provider's system_prompt and the test vars\"",
        "",
        "providers:",
    ]
    for path in variants:
        label = path.stem
        lines += [
            "  - id: file://provider.py",
            f"    label: {_q(label)}",
            "    config:",
            f"      label: {_q(label)}",
            f"      system_prompt: {_q(str(path))}",
            f"      out_dir: {_q(out_dir)}",
            f"      temperature: {temperature}",
            f"      max_tokens: {max_tokens}",
        ]
    lines += [
        "",
        "tests:",
        "  - vars:",
        f"      text_path: {_q(text)}",
        f"      pathway: {_q(pathway)}",
        f"      organism: {_q(organism)}",
        f"      scope: {_q(scope)}",
        "    # No automated assertions. The comparison is by eye, by design: a count",
        "    # threshold here would decide the question the reading is meant to settle.",
        "",
        "# Identical legs differ even at temperature 0. Use `--repeat 3` before trusting",
        "# any difference between two variants.",
    ]
    return "\n".join(lines) + "\n"


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    ap.add_argument("--variants", required=True, help="directory holding v*.txt variants")
    ap.add_argument("--text", required=True)
    ap.add_argument("--pathway", default="")
    ap.add_argument("--organism", default="")
    ap.add_argument("--scope", default="")
    ap.add_argument("--out-dir", required=True, help="where payloads and summaries are written")
    ap.add_argument("--temperature", type=float, default=0.0)
    ap.add_argument("--max-tokens", type=int, default=0,
                    help="0 leaves it to the provider, which reads the app's own budget")
    ap.add_argument("--config", default=str(HERE / "promptfooconfig.yaml"))
    args = ap.parse_args(list(argv) if argv is not None else None)

    vdir = Path(args.variants)
    if not vdir.is_dir():
        raise SystemExit(f"no such variants directory: {vdir}")
    # ABSOLUTE, always: the provider resolves a relative path against ITS OWN directory,
    # so a relative --variants argument sent every lookup to
    # docs/evaluation_v2/promptfoo/docs/evaluation_v2/prompt_variants/... and errored all
    # ten rows before a single call was billed.
    variants = sorted(p.resolve() for p in vdir.glob("v*.txt") if p.is_file())
    if not variants:
        raise SystemExit(f"no v*.txt variants in {vdir}")

    text = Path(args.text)
    if not text.is_file():
        raise SystemExit(f"no such paper text: {text}")

    config = build(variants, text=str(text.resolve()), pathway=args.pathway, organism=args.organism,
                   scope=args.scope, out_dir=args.out_dir,
                   temperature=args.temperature, max_tokens=args.max_tokens)
    Path(args.config).write_text(config, encoding="utf-8")

    print(f"wrote {args.config}")
    print(f"{len(variants)} variant(s):")
    for p in variants:
        print(f"  {p.stem:28s} {p.stat().st_size:7d} bytes  {p}")
    print()
    print(f"one draw each = {len(variants)} billed extraction call(s); "
          f"with --repeat 3, {len(variants) * 3}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
